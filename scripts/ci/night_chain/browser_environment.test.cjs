'use strict';
const assert=require('node:assert/strict');
const {browserEnvironment}=require('./browser_environment.cjs');
const base=Object.freeze({HOME:'/isolated/application/home',ASTROPILOT_DATA_DIR:'/isolated/data',USERPROFILE:'/isolated/home',APPDATA:'/isolated/appdata',LOCALAPPDATA:'/isolated/localappdata',TMPDIR:'/isolated/tmp',BROWSER_NATIVE_HOME:'/Users/runner',BROWSER_NATIVE_USERPROFILE:'C:\\Users\\runneradmin',GITHUB_ACTIONS:'true'});
const mac=browserEnvironment(base,{platform:'darwin'});
assert.equal(mac.HOME,'/Users/runner');assert.equal(base.HOME,'/isolated/application/home');
assert.deepEqual(Object.keys(mac).filter(k=>mac[k]!==base[k]),['HOME']);
const win=browserEnvironment(base,{platform:'win32'});
assert.equal(win.USERPROFILE,'C:\\Users\\runneradmin');
assert.equal(base.USERPROFILE,'/isolated/home');
assert.deepEqual(Object.keys(win).filter(k=>win[k]!==base[k]),['USERPROFILE']);
assert.deepEqual(browserEnvironment({...base,GITHUB_ACTIONS:undefined},{platform:'win32'}),{...base,GITHUB_ACTIONS:undefined});
assert.throws(()=>browserEnvironment({...base,BROWSER_NATIVE_USERPROFILE:undefined},{platform:'win32'}));
assert.throws(()=>browserEnvironment({...base,BROWSER_NATIVE_USERPROFILE:'relative/profile'},{platform:'win32'}));
assert.deepEqual(browserEnvironment({...base,GITHUB_ACTIONS:undefined},{platform:'darwin'}),{...base,GITHUB_ACTIONS:undefined});
assert.throws(()=>browserEnvironment({...base,BROWSER_NATIVE_HOME:undefined},{platform:'darwin'}));
assert.throws(()=>browserEnvironment({...base,BROWSER_NATIVE_HOME:'relative/home'},{platform:'darwin'}));
console.log('Browser OS identity regression: native HOME on Mac / USERPROFILE on Windows for CI browser child only; app/data/temp and local user unchanged');
