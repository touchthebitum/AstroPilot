"""Internal installation qualification. Public seeded data; no host Windows install."""
from pathlib import Path
import argparse,json,os,secrets,shutil,subprocess,sys,time
import base_controller as c
OLD='3cd135644ba8f306c15291073b52c469059247b0'
MARKER='NIGHTMERIT-PUBLIC-INSTALLATION-TEST-7e98e45'

def windows_allowed():
 if os.name!='nt':return
 sandbox=os.environ.get('USERNAME','').casefold()=='wdagutilityaccount' and Path('C:/NightMeritInput/kit.json').is_file()
 # CI runs on a disposable hosted VM; this path is never enabled by the human launcher.
 ci=os.environ.get('GITHUB_ACTIONS')=='true' and os.environ.get('RUNNER_ENVIRONMENT')=='github-hosted'
 if not (sandbox or ci):raise RuntimeError('Installation refusée sur le PC habituel. Utilisez LANCER-TEST-WINDOWS.cmd : le test exige Windows Sandbox.')

def inside(path,root):
 path=path.resolve();root=root.resolve()
 if not path.is_relative_to(root) or path==root:raise RuntimeError('Opération extérieure à la copie isolée refusée.')
 return path

class Installation(c.Controller):
 def __init__(self,kit,case,lab=False):
  windows_allowed()
  super().__init__(kit,case,lab)
  self.app.executable=self.executable()
  if self.state.get('site'):
   # super only starts when resuming: its default executable must match installed payload.
   raise RuntimeError('Reprise constructeur invalide')
 def executable(self):return self.case/'installation/candidate'/('AstroPilot.exe' if os.name=='nt' else 'AstroPilot.app/Contents/MacOS/AstroPilot')
 def save(self):super().save()
 def install(self,which):
  dest=inside(self.case/'installation/candidate',self.case);dest.parent.mkdir(parents=True,exist_ok=True)
  if os.name=='nt':
   setup=self.kit/('previous-setup.exe' if which=='previous' else 'candidate-setup.exe')
   args=[str(setup),'/VERYSILENT','/SUPPRESSMSGBOXES','/NORESTART','/SP-','/NOICONS','/DIR='+str(dest),'/LOG='+str(self.case/(which+'-installation.log'))]
   with (self.case/'installer-output.log').open('ab') as log:
    run=c.run_external(args,env=self.app.env(),stdout=log,stderr=log,timeout=240)
   if run.returncode!=0:raise RuntimeError('Échec de l’installeur : '+str(run.returncode))
  else:
   staged=inside(self.case/'installation/staged',self.case)
   if staged.exists():raise RuntimeError('Un dossier de préparation existe déjà ; copie conservée pour diagnostic.')
   staged.mkdir();c.run_external(['/usr/bin/ditto',str(self.kit/which/'AstroPilot.app'),str(staged/'AstroPilot.app')],check=True,timeout=120)
   c.run_external(['/usr/bin/codesign','--verify','--deep','--strict',str(staged/'AstroPilot.app')],check=True,timeout=60)
   if dest.exists():shutil.rmtree(dest)
   staged.rename(dest)
  self.app.executable=self.executable();self.app.expected_sha=OLD if which=='previous' else c.SHA
  self.state.setdefault('operations',[]).append({'action':'install','source_sha':self.app.expected_sha,'method':'official_installer' if os.name=='nt' else 'isolated_app_copy','exit_code':0});self.save()
 def remove_application(self):
  dest=inside(self.case/'installation/candidate',self.case)
  if os.name=='nt':
   uninstaller=dest/'unins000.exe'
   if not uninstaller.is_file():raise RuntimeError('Désinstalleur isolé manquant.')
   with (self.case/'installer-output.log').open('ab') as log:
    run=c.run_external([str(uninstaller),'/VERYSILENT','/SUPPRESSMSGBOXES','/NORESTART','/LOG='+str(self.case/'uninstall.log')],env=self.app.env(),stdout=log,stderr=log,timeout=120)
   if run.returncode!=0:raise RuntimeError('Échec de la désinstallation isolée.')
   for _ in range(100):
    if not self.executable().exists():break
    time.sleep(.1)
   if self.executable().exists():raise RuntimeError('L’exécutable reste présent après désinstallation.')
  else:shutil.rmtree(dest)
  self.state.setdefault('operations',[]).append({'action':'uninstall','data_unchanged':c.authority(self.case/'data')==self.baseline});self.save()
  if c.authority(self.case/'data')!=self.baseline:raise RuntimeError('La désinstallation a changé les données de test.')
 def start(self,site=None):
  if self.state['phase']!='new':raise RuntimeError('Ce test existe déjà. Ne recréez ni session ni crédit.')
  if (self.case/'data').exists():raise RuntimeError('Une copie de données existe déjà : elle est conservée sans remplacement.')
  shutil.copytree(self.kit/'seed',self.case/'data',symlinks=False)
  self.baseline=c.authority(self.case/'data');c.write(self.case/'before-installation.json',self.baseline)
  seed=json.loads((self.kit/'seed-provenance.json').read_text(encoding='utf-8'))
  self.state.update(site='zurich',phase='running',night_date=seed['night_date'],availability=seed['availability'],qualification='installation-upgrade-reinstall',baseline_source_sha=OLD,seeded_existing_credits=True)
  self.forecast.site=c.SITES['zurich'];self.save()
  # First the previous official candidate with the exact public profile generated by it.
  self.install('previous');self.app.start()
  if not self.inspect()['ready']:raise RuntimeError('Les crédits de référence ne sont pas cohérents.')
  self.app.stop()
  if c.authority(self.case/'data')!=self.baseline:raise RuntimeError('Le lancement de référence a modifié les fichiers canoniques.')
  # Upgrade in place, without moving or regenerating the profile.
  self.install('candidate');self.app.start()
  if not self.inspect()['ready'] or c.authority(self.case/'data')!=self.baseline:raise RuntimeError('La mise à niveau n’a pas conservé les crédits.')
  super().restart(True);self.state['automatic_checks']={'upgrade_replays':list(self.state['replays'])};self.app.stop()
  self.remove_application();self.install('candidate');self.app.start()
  if not self.inspect()['ready'] or c.authority(self.case/'data')!=self.baseline:raise RuntimeError('La réinstallation n’a pas conservé les crédits.')
  super().restart(True);self.state['automatic_checks']['reinstall_replays']=list(self.state['replays'])
  self.state['user_confirmations']={};self.state['automatic_installation_pass']=True;self.state['canonical_bytes_unchanged']=True;self.save()
 def export(self,confirmed=False,incomplete=False):
  if not incomplete and confirmed is True:self.state['user_confirmations']['before_restart']=True
  if self.exported:return self.exported
  output=super().export(confirmed,incomplete)
  # Only explicit test logs are added; profiles, certificates and browser state stay local.
  import zipfile
  with zipfile.ZipFile(output,'a',zipfile.ZIP_DEFLATED) as z:
   for p in self.case.glob('*installation.log'):z.write(p,p.name)
   for name in ['uninstall.log','installer-output.log']:
    p=self.case/name
    if p.is_file():z.write(p,name)
  if os.name=='nt' and Path('C:/NightMeritResults').is_dir():shutil.copy2(output,Path('C:/NightMeritResults')/Path(output).name)
  return output

def resume(kit,case,lab):
 windows_allowed()
 if not (case/'INSTALLATION-TEST-UNIQUEMENT').is_file() or (case/'INSTALLATION-TEST-UNIQUEMENT').read_text()!=MARKER:raise RuntimeError('La reprise ne désigne pas une copie de ce kit.')
 state=json.loads((case/'run.json').read_text())
 if not state.get('automatic_installation_pass'):raise RuntimeError('Test interrompu : exporter le diagnostic existant avant de créer un nouveau test. Aucune donnée ne sera réinitialisée.')
 x=Installation.__new__(Installation)
 import threading
 x.kit=kit;x.case=case;x.lab=state['laboratory'];x.lock=threading.Lock();x.error=None;x.closed=threading.Event();x.closing=False;x.browser=None;x.exported=None;x.state=state
 x.forecast=c.Forecast(case);x.forecast.__enter__();x.forecast.site=c.SITES['zurich'];x.app=c.App(kit,case,x.forecast);x.app.executable=x.executable();x.baseline=json.loads((case/'before-installation.json').read_text());x.app.start()
 if not x.inspect()['ready'] or c.authority(case/'data')!=x.baseline:raise RuntimeError('La reprise ne retrouve pas les crédits attendus.')
 x.state['phase']='replayed';return x

def main():
 if '--ignore-browser' in sys.argv:return
 p=argparse.ArgumentParser();p.add_argument('--laboratory',action='store_true');p.add_argument('--no-browser',action='store_true');p.add_argument('--kit-root');p.add_argument('--verify-only',action='store_true');p.add_argument('--resume',action='store_true');a=p.parse_args()
 kit=Path(a.kit_root).resolve() if a.kit_root else Path(sys.executable).resolve().parent.parent
 c.verify(kit)
 if a.verify_only:print('Kit intègre.',flush=True);return
 windows_allowed();copies=kit/'COPIES-ISOLEES';copies.mkdir(exist_ok=True)
 if a.resume:
  case=Path(json.loads((kit/'derniere-copie.json').read_text())['path']).resolve()
  if case.parent!=copies.resolve() or (case/'data').is_symlink():raise RuntimeError('Copie de reprise extérieure refusée.')
  x=resume(kit,case,a.laboratory)
 else:
  case=copies/(c.datetime.now().strftime('%Y%m%d-%H%M%S')+'-'+secrets.token_hex(3));case.mkdir();(case/'INSTALLATION-TEST-UNIQUEMENT').write_text(MARKER);c.write(kit/'derniere-copie.json',{'path':str(case)});x=Installation(kit,case,a.laboratory)
 server,url=c.serve(x);print('Guide : '+url+'\nGardez cette fenêtre ouverte.',flush=True)
 try:
  if not a.no_browser:c.browser(x,url)
  while not x.closed.wait(.25):
   if x.browser and x.browser.poll() is not None and not x.closing:x.error='Navigateur fermé : diagnostic incomplet exporté.';x.shutdown()
 except KeyboardInterrupt:x.shutdown()
 finally:
  server.shutdown()
  if not x.closed.is_set():x.shutdown()
  if x.exported:print('Résultats : '+x.exported,flush=True)
 # The sandbox maps only this results directory back to the host.
 if os.name=='nt' and Path('C:/NightMeritResults').is_dir() and x.exported:shutil.copy2(x.exported,Path('C:/NightMeritResults')/Path(x.exported).name)
if __name__=='__main__':
 try:main()
 except Exception as e:print('Test non validé : '+str(e),flush=True);sys.exit(1)
